def clean_and_lemmatize(text):
    """Очистка и лемматизация текста."""
    if not isinstance(text, str):
        return []
    text = re.sub(r'[^а-яёА-ЯЁ\s]', ' ', text.lower())
    tokens = text.split()
    lemmas = []
    for token in tokens:
        if len(token) < 3 or token in STOPWORDS:
            continue
        lemma = morph.parse(token)[0].normal_form
        if lemma not in STOPWORDS and len(lemma) >= 3:
            lemmas.append(lemma)
    return lemmas


def tag_aspects(lemmas, aspect_dict):
    """Проставляет теги аспектов для одного отзыва."""
    lemma_set = set(lemmas)
    found = [aspect for aspect, words in aspect_dict.items()
             if lemma_set & set(words)]
    return found if found else ['другое']


def build_aspect_dict(seeds, candidate_pool=None):
    """Расширяет словари аспектов через корни слов."""
    aspect_dict = {}
    for aspect, seed_words in seeds.items():
        expanded = set(seed_words)
        if candidate_pool:
            for seed in seed_words:
                root = seed[:5]
                for word in candidate_pool:
                    if root in word:
                        expanded.add(word)
        aspect_dict[aspect] = list(expanded)
    return aspect_dict
